#!/usr/bin/env python3
"""
Generate the SG-1000 test level for the SMB3-physics port.

Layout is original: a 24-row (192 px) tall, LEVEL_W-columns wide strip stored
column-major (24 bytes per column, top to bottom) so the scrolling camera can
stream one screen column at a time into the VDP name table.

Tile indices come from tools/make_tiles.py:
 0 blank, 1 ground top, 2 ground fill, 3 brick, 4 question, 5 used,
 6/7 pipe top L/R, 8/9 pipe body L/R, 10 hard block, 11 coin, 12 cloud
"""
import os

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROWS = 24
W = 176  # columns (1408 px wide)

BLANK, GTOP, GFILL, BRICK, QUEST, USED = 0, 1, 2, 3, 4, 5
PIPETL, PIPETR, PIPEL, PIPER, HARD, COIN, CLOUD = 6, 7, 8, 9, 10, 11, 12

grid = [[BLANK] * W for _ in range(ROWS)]


def ground(c0, c1):
    for c in range(c0, c1 + 1):
        grid[ROWS - 2][c] = GTOP
        grid[ROWS - 1][c] = GFILL


def pipe(c, h):
    top = ROWS - 2 - h
    grid[top][c] = PIPETL
    grid[top][c + 1] = PIPETR
    for r in range(top + 1, ROWS - 2):
        grid[r][c] = PIPEL
        grid[r][c + 1] = PIPER


def blockrow(r, c, tiles):
    for i, t in enumerate(tiles):
        grid[r][c + i] = t


def stairs(c, h, flip=False):
    for i in range(h):
        col = c + (h - 1 - i if flip else i)
        for k in range(i + 1):
            grid[ROWS - 3 - k][col] = HARD


# --- ground with two pits ---
ground(0, 58)
ground(62, 99)
ground(104, W - 1)

# --- opening: question block + brick row ---
blockrow(ROWS - 8, 16, [QUEST])
blockrow(ROWS - 8, 20, [BRICK, QUEST, BRICK, QUEST, BRICK])
blockrow(ROWS - 12, 21, [BRICK, BRICK, BRICK])

# --- clouds ---
for c in (6, 7, 8, 30, 31, 44, 45, 46, 74, 75, 118, 119):
    grid[4][c] = CLOUD

# --- pipes ---
pipe(28, 2)
pipe(40, 3)
pipe(52, 4)

# --- coin arcs over the pits and along the way ---
for c in (60, 61, 101, 102, 103):
    grid[ROWS - 6][c] = COIN
for c in range(66, 72):
    grid[ROWS - 7][c] = COIN
blockrow(ROWS - 8, 84, [COIN, COIN, COIN])

# --- mid brick / question field ---
blockrow(ROWS - 8, 88, [BRICK, QUEST, BRICK])
blockrow(ROWS - 12, 90, [QUEST, BRICK, QUEST])

# --- staircase up, gap, staircase down (hard blocks) ---
stairs(110, 4)
stairs(116, 4, flip=True)
stairs(124, 5)
stairs(131, 5, flip=True)

# --- coin room reward ---
for c in range(140, 148):
    grid[ROWS - 6][c] = COIN

# --- end wall ---
for r in range(ROWS - 10, ROWS - 2):
    grid[r][W - 4] = HARD
    grid[r][W - 3] = HARD

# sanity: report tile counts
counts = {}
for r in range(ROWS):
    for c in range(W):
        counts[grid[r][c]] = counts.get(grid[r][c], 0) + 1

lines = ["; --- generated by tools/make_level.py ---",
         "LEVEL_ROWS:\t.equ %d" % ROWS,
         "LEVEL_W:\t.equ %d" % W,
         "; column-major: 24 bytes per column, top row first",
         "LevelData:"]
for c in range(W):
    col = [grid[r][c] for r in range(ROWS)]
    for i in range(0, ROWS, 12):
        lines.append("\t.db " + ",".join(str(v) for v in col[i:i + 12]))
lines.append("")
# solid map: bit per tile index (0..15)
solid = {GTOP: 1, GFILL: 1, BRICK: 1, QUEST: 1, USED: 1, PIPETL: 1, PIPETR: 1,
         PIPEL: 1, PIPER: 1, HARD: 1}
bits = 0
for t in range(16):
    if solid.get(t):
        bits |= 1 << t
lines.append("; solidity bitmask, one bit per tile index 0-15")
lines.append("TileSolidMask:\t.equ $%04X" % bits)

gen = os.path.join(REPO, "sg1000", "gen")
os.makedirs(gen, exist_ok=True)
with open(os.path.join(gen, "level.z80"), "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote gen/level.z80", W, "columns;", counts)

# preview
from PIL import Image
S = 3
img = Image.new("RGB", (W * 8 * S // 4, ROWS * 8 * S // 4), (128, 118, 241))
pal = {1: (230, 201, 95), 2: (120, 90, 20), 3: (202, 69, 60), 4: (230, 201, 95),
       5: (150, 120, 40), 6: (116, 208, 125), 7: (46, 139, 87), 8: (116, 208, 125),
       9: (46, 139, 87), 10: (230, 201, 95), 11: (255, 220, 80), 12: (255, 255, 255)}
px = img.load()
for r in range(ROWS):
    for c in range(W):
        t = grid[r][c]
        if t:
            col = pal[t]
            for y in range(8 * S // 4):
                for x in range(8 * S // 4):
                    px[c * 8 * S // 4 + x, r * 8 * S // 4 + y] = col
img.save(os.path.join(gen, "level_preview.png"))
print("wrote gen/level_preview.png")
