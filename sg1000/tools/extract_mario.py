#!/usr/bin/env python3
"""
Extract SMB3 small-Mario sprite frames from the repo's CHR pages and convert
them into TMS9918A (SG-1000) 16x16 sprite patterns, one pattern per colour so
that Mario can be drawn with exactly 3 colours using 3 stacked sprites.

Source of truth: CHR/chr083.pcx  (NES VROM page $53 = small Mario page offset 3)
Frame layout (from PRG/prg029.asm SPPF_Table): a small-Mario frame is two 8x16
sprites whose OAM pattern bytes are (p, p+2).  Inside the CHR page the four
8x8 tiles of the 16x16 frame sit at page positions p-1 (top-left), p (bottom-left),
p+1 (top-right), p+2 (bottom-right).

PCX grey levels encode the NES colour index:
   0   -> transparent
   255 -> colour 1 (red   : NES $16)
   170 -> colour 2 (skin  : NES $36)
   85  -> colour 3 (dark  : NES $0F)
"""
import os
import sys
from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PAGE = 83  # chr083.pcx == VROM page $53 (small Mario, page offset 3)

GREY2IDX = {0: 0, 85: 3, 170: 2, 255: 1}

# frame name -> OAM pattern byte of the left 8x16 sprite (PRG029 SPPF_Table)
FRAMES = [
    ("stand",  0x05),   # PF3E walk-small base / standing
    ("walk1",  0x01),   # PF3F walk-small frame 2
    ("jump",   0x19),   # PF40 jump / fall small
    ("skid",   0x21),   # PF41 skid small
    ("run0",   0x31),   # PF4C run small 0
    ("run1",   0x35),   # PF4D run small 1
]

# TMS9918 sprite colour codes used for the three masks
COL_RED, COL_SKIN, COL_DARK = 8, 11, 1


def load_tiles(page):
    im = Image.open(os.path.join(REPO, "CHR", "chr%03d.pcx" % page)).convert("L")
    tiles = []
    for t in range(64):
        x, y = (t % 16) * 8, (t // 16) * 8
        px = im.crop((x, y, x + 8, y + 8)).load()
        tiles.append([[GREY2IDX[px[i, j]] for i in range(8)] for j in range(8)])
    return tiles


def frame_bitmap(tiles, p):
    """Return 16x16 list of rows of colour indices (0 transparent,1,2,3)."""
    tl, bl, tr, br = tiles[p - 1], tiles[p], tiles[p + 1], tiles[p + 2]
    bmp = []
    for j in range(8):
        bmp.append(tl[j] + tr[j])
    for j in range(8):
        bmp.append(bl[j] + br[j])
    return bmp


def mask_bytes(bmp, idx, mirror=False):
    """16x16 one-bit mask -> 32 bytes, TMS9918 16x16 layout TL,TR,BL,BR."""
    if mirror:
        bmp = [row[::-1] for row in bmp]
    halves = [
        [row[0:8] for row in bmp],     # left 8 columns, rows 0-15
        [row[8:16] for row in bmp],    # right 8 columns, rows 0-15
    ]
    out = []
    for q in halves:
        for row in q:
            b = 0
            for bit in row:
                b = (b << 1) | (1 if bit == idx else 0)
            out.append(b)
    return out


def main():
    tiles = load_tiles(PAGE)
    lines = []
    lines.append("; --- generated by tools/extract_mario.py ---")
    lines.append("; SMB3 small Mario, 3 colour layers (red/skin/dark).")
    lines.append("; Groups ordered (frame, direction, layer); a group is a 16x16")
    lines.append("; TMS9918 sprite pattern of 32 bytes. SAT pattern byte = group*4.")
    lines.append("MARIO_NFRAMES:\t.equ %d" % len(FRAMES))
    lines.append("MARIO_NGROUPS:\t.equ %d" % (len(FRAMES) * 2 * 3))
    lines.append("MARIO_COL_RED:\t.equ %d" % COL_RED)
    lines.append("MARIO_COL_SKIN:\t.equ %d" % COL_SKIN)
    lines.append("MARIO_COL_DARK:\t.equ %d" % COL_DARK)
    lines.append("")

    # preview image
    S = 8
    prev = Image.new("RGB", ((16 * S + 8) * len(FRAMES), 16 * S + 8), (30, 30, 60))
    pal = {0: (30, 30, 60), 1: (216, 40, 0), 2: (252, 216, 168), 3: (40, 20, 0)}

    groups = []  # (label, bytes)
    for name, p in FRAMES:
        bmp = frame_bitmap(tiles, p)
        img = Image.new("RGB", (16, 16))
        px = img.load()
        for j in range(16):
            for i in range(16):
                px[i, j] = pal[bmp[j][i]]
        k = FRAMES.index((name, p))
        prev.paste(img.resize((16 * S, 16 * S), Image.NEAREST), (k * (16 * S + 8), 8))
        for dirn, mir in (("r", False), ("l", True)):
            for layer, idx in (("red", 1), ("skin", 2), ("dark", 3)):
                groups.append(("%s_%s_%s" % (name, dirn, layer),
                               mask_bytes(bmp, idx, mir)))

    lines.append("MarioPatterns:")
    for label, data in groups:
        lines.append("\t; %s" % label)
        for i in range(0, 32, 8):
            lines.append("\t.db " + ",".join("$%02X" % b for b in data[i:i + 8]))
    lines.append("")

    gen = os.path.join(REPO, "sg1000", "gen")
    os.makedirs(gen, exist_ok=True)
    with open(os.path.join(gen, "mario_sprites.z80"), "w") as f:
        f.write("\n".join(lines) + "\n")
    prev.save(os.path.join(gen, "mario_preview.png"))
    print("wrote gen/mario_sprites.z80 and gen/mario_preview.png")


if __name__ == "__main__":
    main()
